#!/usr/bin/env python3
"""Inventory bundled assets and create a transportable source + offline preview archive."""
from pathlib import Path
import hashlib,json,zipfile,sys
root=Path(__file__).resolve().parents[1]
# Runtime assets are already present. No outside source folders are needed to rebuild.
try:
 from PIL import Image
except ImportError:
 Image=None
entries=[]
for p in sorted((root/'public').rglob('*')):
 if not p.is_file():continue
 rel=p.relative_to(root).as_posix()
 origin='DOWN THE PIGEONHOLE 2026-10-17/site/'+p.relative_to(root/'public').as_posix()
 if '/generated/' in rel:origin='Built-in ImageGen / October 18, 2026 / docs/prompts.json'
 elif 'unlicensed.' in rel:origin='Derived delivery copy of generated vista or generated depth estimate'
 elif p.name=='water_tower.glb':origin='city-has-other-plans/public/assets/props/water_tower.glb'
 elif p.name in ('collection.html','catalog.json'):origin='Generated by tools/catalog.mjs from src/catalog.js'
 row={'path':rel,'bytes':p.stat().st_size,'sha256':hashlib.sha256(p.read_bytes()).hexdigest(),'origin':origin}
 if Image and p.suffix.lower() in ('.png','.jpg','.jpeg'):
  with Image.open(p) as im:row['dimensions']=list(im.size)
 entries.append(row)
(root/'docs/asset-manifest.json').write_text(json.dumps({'fullResolutionOriginalsIncluded':False,'entries':entries},indent=2))
files=[]
for p in sorted(root.rglob('*')):
 if not p.is_file() or p.is_symlink():continue
 rel=p.relative_to(root)
 if any(x in ('node_modules','.git','__pycache__','.vite','.vite-temp') for x in rel.parts):continue
 if p.name.startswith('.env') or p.name=='.DS_Store' or p.suffix in ('.zip','.pyc','.log'):continue
 if p.name=='package-files.sha256':continue
 files.append(p)
(root/'docs/package-files.sha256').write_text(''.join(hashlib.sha256(p.read_bytes()).hexdigest()+'  '+p.relative_to(root).as_posix()+'\n' for p in files))
files.append(root/'docs/package-files.sha256')
out=root.parent/'deliverables/UNLICENSED-NEW-YORK-source-2026-10-18.zip';out.parent.mkdir(exist_ok=True)
with zipfile.ZipFile(out,'w',zipfile.ZIP_DEFLATED,compresslevel=6) as z:
 for p in files:z.write(p,root.name+'/'+p.relative_to(root).as_posix())
with zipfile.ZipFile(out) as z:
 assert z.testzip() is None
 assert not any('/node_modules/' in n or '/.env' in n for n in z.namelist())
h=hashlib.sha256(out.read_bytes()).hexdigest();out.with_suffix('.zip.sha256').write_text(h+'  '+out.name+'\n')
print(json.dumps({'archive':str(out),'files':len(files),'bytes':out.stat().st_size,'sha256':h},indent=2))
