#!/usr/bin/env python3
"""barney_art.py: the Barney Greengrass merch on the walls of museum room 123.

MLow picked 43 of the 145 Moe's Chachkas graphics into his own folder (the Finder tagged set), and on
2026-10-12 corrected Gary's likeness on seven of them in ChatGPT. This script takes the current final
of each pick from the collab ledger (the v3 likeness files where they exist), dithers it with the house
recipe (ditherlab fs32x2: OKLab Floyd Steinberg, 32 colours on a 2 px grid, the visible census dither),
writes a small PNG per piece to assets/museum/barney/, and writes the manifest the room reads
(_build/museum/src/rooms/barney_art.ts): file, aspect, number, title line, medium, and whether the
likeness was corrected. Originals are never touched. Re running skips pieces whose PNG is newer than
its source.

    python3 barney_art.py            # all picks
    python3 barney_art.py --w 768    # a different width (default 1024)
"""
import argparse, json, os, re, sys, time
HERE = os.path.dirname(os.path.abspath(__file__)); SITE = os.path.dirname(HERE); ROOT = os.path.dirname(SITE)
COLLAB = os.path.join(ROOT, 'BARNEY GREENGRASS COLLAB 2026-09-03')
PICKS = os.path.join(COLLAB, 'likeness_2026-10-12', 'finder-tags.json')  # MLow's 43 picks, the Finder tagged mock ups folder as listed on 2026-10-12
OUT = os.path.join(SITE, 'assets', 'museum', 'barney')
TS = os.path.join(HERE, 'museum', 'src', 'rooms', 'barney_art.ts')
sys.path.insert(0, os.path.join(ROOT, '00_TOOLS', 'ditherlab'))
import ditherlab as D
from PIL import Image

ap = argparse.ArgumentParser(); ap.add_argument('--w', type=int, default=1024); ap.add_argument('--recipe', default='fs32x2'); a = ap.parse_args()
os.makedirs(OUT, exist_ok=True)
ledger = {i['n']: i for i in json.load(open(os.path.join(COLLAB, 'merch', 'LEDGER.json')))}
picks = sorted(int(m.group(1)) for e in json.load(open(PICKS)) if (m := re.match(r'(\d+)_', os.path.basename(e['file']))))
# the order on the walls: the corrected likeness pieces first, then MLow's picks by number
fixed = [n for n in picks if ledger[n].get('v3_file')]
order = fixed + [n for n in picks if n not in fixed]

def medium(src):
    s = src.lower()
    for key, word in [('wpa', 'WPA poster'), ('anime', 'anime key visual'), ('3d animated', '3D animated still'), ('pixar', '3D animated still'), ('trading card', 'trading card'),
                      ('magazine', 'magazine cover'), ('bullfight', 'bullfight poster'), ('boxing', 'fight poster'), ('propaganda', 'propaganda poster'), ('travel', 'travel poster'),
                      ('film poster', 'film poster'), ('record', 'record sleeve'), ('tee', 'tee graphic'), ('poster', 'poster')]:
        if key in s: return word
    return 'merch graphic'

items = []; t0 = time.time()
for n in order:
    L = ledger[n]
    src = os.path.join(COLLAB, 'merch', L['final'])
    dst = os.path.join(OUT, f'{n:03d}.png')
    if not (os.path.exists(dst) and os.path.getmtime(dst) > os.path.getmtime(src)):
        out, k = D.render(src, a.recipe, out_w=a.w); out.save(dst, 'PNG', optimize=True)
        print(f'{n:3d} {L["slug"]:34s} {k} colours {os.path.getsize(dst) // 1024} KB', flush=True)
    w, h = Image.open(dst).size
    line = L.get('line', L['slug'].replace('-', ' ').upper())
    items.append({'n': n, 'f': f'assets/museum/barney/{n:03d}.png', 'ar': round(w / h, 4), 't': line, 'm': medium(L.get('source', '')), 'fix': bool(L.get('v3_file'))})

with open(TS, 'w') as f:
    f.write('/* Generated by _build/barney_art.py: the Moe\'s Chachkas merch on the walls of room 123, dithered. Do not edit by hand. */\n')
    f.write('export type BarneyArt = { n: number; f: string; ar: number; t: string; m: string; fix: boolean };\n')
    f.write('export const BARNEY_ART: BarneyArt[] = ' + json.dumps(items, ensure_ascii=False, separators=(',', ':')) + ';\n')
total = sum(os.path.getsize(os.path.join(OUT, '%03d.png' % i['n'])) for i in items) // 1024
print('%d pieces, %d with the corrected likeness, %d KB, %.0fs' % (len(items), sum(1 for i in items if i['fix']), total, time.time() - t0))
